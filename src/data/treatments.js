// A bag line is a treatment when it carries a duration; products do not.
export function isTreatmentItem(item) {
  return Boolean(item?.duration);
}

// Only a priced treatment can go in the bag: checkout prices every line from
// catalogueIndex.js and refuses one with no price.
export function isBookableOnline(treatment) {
  return typeof treatment.price === "number";
}

// A treatment shown in more than one category keeps one page (its slug) and
// one home category; `alsoListedIn` names each further category and the
// subcategory it sits under there.
export function isListedInCategory(treatment, categoryId) {
  return treatment.category === categoryId
    || Boolean(treatment.alsoListedIn?.some(listing => listing.category === categoryId));
}

// A category's treatments in display order: its own first, then those listed
// in it from elsewhere, so the extra listings never reorder its headings.
export function listingsInCategory(categoryId, list = treatments) {
  const own = list.filter(t => t.category === categoryId);
  const fromElsewhere = list.flatMap(t => {
    const listing = t.category !== categoryId && t.alsoListedIn?.find(l => l.category === categoryId);
    return listing ? [{ ...t, subcategory: listing.subcategory }] : [];
  });
  return [...own, ...fromElsewhere];
}
